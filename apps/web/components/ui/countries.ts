// All ISO 3166-1 countries, name + flag emoji. Flag emojis render with the
// system font on every modern OS (macOS, iOS, Android, Win 11 with the
// emoji font installed); Win 10 falls back to "GB", "US", etc. text, which
// is still readable. The list is sorted alphabetically by display name so
// the dropdown is browsable without a search box for now.
//
// Stored value is the country's English display name (the same string that
// already lives in DB columns today). The flag is rendered for the dropdown
// label and the selected display but not persisted, so existing rows with
// free-text country strings continue to render.

export interface Country {
  /** ISO 3166-1 alpha-2 code — lower-cased ASCII letters. */
  code: string
  /** English display name. This is what gets stored. */
  name: string
  /** Flag emoji (two regional-indicator code points). */
  flag: string
}

function flagFor(code: string): string {
  const upper = code.toUpperCase()
  const offset = 0x1f1e6 - 'A'.charCodeAt(0)
  return (
    String.fromCodePoint(upper.charCodeAt(0) + offset) +
    String.fromCodePoint(upper.charCodeAt(1) + offset)
  )
}

