export const COUNTRIES: readonly Country[] = NAMES.map(([code, name]) => ({
  code,
  name,
  flag: flagFor(code),
})).sort((a, b) => a.name.localeCompare(b.name))

const NAME_TO_FLAG: Map<string, string> = new Map(
  COUNTRIES.map((c) => [c.name.toLowerCase(), c.flag]),
)

/** Look up a flag for a country name (case-insensitive). Returns '' if
 * the name doesn't match — keeps free-text rows rendering cleanly. */
export function flagForCountryName(name: string | null | undefined): string {
  if (!name) return ''
  return NAME_TO_FLAG.get(name.trim().toLowerCase()) ?? ''
}
