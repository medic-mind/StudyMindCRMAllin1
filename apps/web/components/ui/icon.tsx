// Inline SVG icon library. CLAUDE.md §4 (Lucide style, no emoji), §3 (no
// new deps without ADR). We hand-roll a small set so we stay dep-free
// while matching Lucide's visual language (24px grid, 2px stroke, round
// caps, round joins). Add only what we need.

import type { SVGProps } from 'react'

type IconProps = SVGProps<SVGSVGElement> & {
  /** Pixel size — defaults to 16 (compact toolbar icons). */
  size?: number
}

function base({ size = 16, strokeWidth = 2, ...rest }: IconProps) {
  return {
    width: size,
    height: size,
    viewBox: '0 0 24 24',
    fill: 'none' as const,
    stroke: 'currentColor',
    strokeWidth,
    strokeLinecap: 'round' as const,
    strokeLinejoin: 'round' as const,
    'aria-hidden': true as const,
    ...rest,
  }
}

